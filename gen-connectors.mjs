/**
 * Writes connectors to `connectors/<slug>/`.
 *
 * Every entry in `connectors.data.mjs` was verified before being written:
 *
 *   1. The npm package resolves on the public registry, so `npx -y <pkg>` has a
 *      real thing to fetch. Plausible-looking names that do not exist were
 *      dropped rather than shipped — a connector that cannot install is worse
 *      than one that is missing.
 *   2. Simple Icons publishes a mark under the given title, so the card renders a
 *      genuine brand logo rather than something drawn by hand.
 *
 * Icons are not fetched here. `build-icons.mjs` is the single place that talks to
 * Simple Icons, and it writes both the per-connector `icon.svg` and the committed
 * icon data module. Run it after this.
 *
 *   node gen-connectors.mjs && node build-icons.mjs
 *
 * Existing directories are never overwritten, so this is safe to re-run.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CONNECTORS } from "./connectors.data.mjs";
import { DOMAIN_CONNECTORS } from "./connectors-domains.data.mjs";

/*
 * Both batches, generated by one script.
 *
 * The domain batch is kept in its own data file so its provenance stays visible — every entry was
 * checked against the npm registry and the Simple Icons index before being written — but the
 * generator is identical, and duplicating it would mean a manifest-shape change had to be made
 * twice. Concatenated rather than merged so the original file stays reviewable on its own.
 */
const ALL_CONNECTORS = [...CONNECTORS, ...DOMAIN_CONNECTORS];

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "connectors");

/** Renders TOOLS.md, which is the per-tool reference an agent author reads. */
function toolsDoc(connector) {
  const lines = [
    `# ${connector.title} — tools`,
    "",
    "Reference for every tool this connector exposes. Agents choose a tool by reading",
    "its description, so each one states precisely what it does.",
    "",
  ];
  for (const tool of connector.tools) {
    lines.push(`## \`${tool.name}\``, "", tool.description, "");
    if (tool.readOnly) lines.push("Read-only — safe to call without confirmation.", "");
    else lines.push("**Writes or changes state.** Confirm before calling.", "");
    const props = Object.entries(tool.params ?? {});
    if (props.length) {
      lines.push("| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |");
      for (const [name, spec] of props) {
        lines.push(
          `| \`${name}\` | ${spec.type} | ${spec.required ? "yes" : "no"} | ${spec.description} |`,
        );
      }
      lines.push("");
    } else {
      lines.push("Takes no parameters.", "");
    }
  }
  return lines.join("\n");
}

function readme(connector) {
  const scopes = connector.scopes.join(", ");
  return `# ${connector.title}

${connector.summary}

- **Category** — ${connector.category}
- **Transport** — stdio
- **Auth** — ${connector.auth}${scopes ? ` (${scopes})` : ""}
- **Type** — Connector (MCP server: callable tools)

## What this is

A [Pocket Connector](https://usepocket.net/connectors): an MCP server exposing
tools an agent can call. A Connector provides *capability*; a Skill provides the
*knowledge* of how to use it well. Many are best installed as a pair.

## Tools

${connector.tools.map((tool) => `- \`${tool.name}\` — ${tool.description}`).join("\n")}

See [TOOLS.md](./TOOLS.md) for parameters.

## Icon

\`icon.svg\` is this connector's official mark **in full brand colour**, rendered on
its marketplace card. It comes from [Simple Icons](https://simpleicons.org), which
publishes brand SVGs and their official hex colours under CC0.

Trademarks belong to their respective owners. A mark here indicates the service
this connector talks to, not endorsement by it.

## Install

Pocket runs the server for you. To run it directly:

\`\`\`bash
npx -y ${connector.package}
\`\`\`

${connector.authNote}
`;
}

let written = 0;
let skipped = 0;

for (const connector of ALL_CONNECTORS) {
  const dir = path.join(root, connector.slug);
  if (fs.existsSync(dir)) {
    skipped += 1;
    continue;
  }
  fs.mkdirSync(dir, { recursive: true });

  const manifest = {
    $schema: "https://usepocket.net/schema/connector.json",
    name: connector.slug,
    summary: connector.summary,
    category: connector.category,
    author: "pocket",
    transport: "stdio",
    command: { run: "npx", args: ["-y", connector.package] },
    auth: connector.auth,
    scopes: connector.scopes,
    tools: connector.tools.map((tool) => {
      const properties = {};
      const required = [];
      for (const [name, spec] of Object.entries(tool.params ?? {})) {
        properties[name] = { type: spec.type, description: spec.description };
        if (spec.required) required.push(name);
      }
      const entry = {
        name: tool.name,
        description: tool.description,
        inputSchema: { type: "object", properties, required },
      };
      // Only read-only tools carry the flag, matching the hand-written manifests:
      // absence means "may change state", which is the safer default to assume.
      if (tool.readOnly) entry.readOnly = true;
      return entry;
    }),
    license: "MIT",
    homepage: connector.homepage,
  };

  fs.writeFileSync(
    path.join(dir, "connector.json"),
    JSON.stringify(manifest, null, 2) + "\n",
    "utf8",
  );
  fs.writeFileSync(path.join(dir, "README.md"), readme(connector), "utf8");
  fs.writeFileSync(path.join(dir, "TOOLS.md"), toolsDoc(connector), "utf8");
  written += 1;
}

console.log(`connectors: ${written} written, ${skipped} already present`);
console.log(`total now: ${fs.readdirSync(root).length}`);
